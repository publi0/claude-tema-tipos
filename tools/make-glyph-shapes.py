#!/usr/bin/env python3
"""Regenerates hooks/glyph-shapes.ts: outlines of the 9 Geist glyphs at weight 500,
17 px, centered like text-anchor=middle + dominant-baseline=central.
Needs fonttools (python3 -m venv .venv && .venv/bin/pip install fonttools).
Usage: .venv/bin/python tools/make-glyph-shapes.py path/to/Geist.ttf"""
import sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

root = Path(__file__).resolve().parent.parent
ttf = sys.argv[1]
font = instantiateVariableFont(TTFont(ttf), {'wght': 500})
upm, asc, desc = font['head'].unitsPerEm, font['hhea'].ascent, font['hhea'].descent
glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
scale, central = 17 / upm, (asc + desc) / 2

lines = [
    '// Generated by tools/make-glyph-shapes.py: outlines of the 9 Geist glyphs (weight 500, 17 px),',
    '// centered in the cell. Geist is OFL-licensed (GEIST-LICENSE.txt).',
    'export const GLYPH_PATHS: readonly string[] = [',
    "  '', // 0: empty",
]
for i, ch in enumerate('.·:-=+*%#', 1):
    g = glyphs[cmap[ord(ch)]]
    pen = SVGPathPen(glyphs, ntos=lambda v: ('%.1f' % v).rstrip('0').rstrip('.'))
    g.draw(TransformPen(pen, (scale, 0, 0, -scale, -g.width * scale / 2, central * scale)))
    lines.append(f"  '{pen.getCommands()}', // {i}: {ch}")
lines.append(']')
(root / 'hooks/glyph-shapes.ts').write_text('\n'.join(lines) + '\n')
